    /// <summary>
    ///     Determines whether the given column should participate in the SELECT-back's WHERE clause as
    ///     an IDENTITY-style lookup (<c>[col] = scope_identity()</c>) versus a parameter-based lookup
    ///     (<c>[col] = @p</c>).
    /// </summary>
    /// <remarks>
    ///     The base class returns <see langword="true" /> whenever the column is <c>IsKey + IsRead</c>,
    ///     which over-matches: a composite PK with an INT IDENTITY column AND a Guid column where both
    ///     are store-generated would have both columns marked <c>IsKey + IsRead</c>. The base WHERE
    ///     clause would emit <c>[IntKey] = scope_identity() AND [GuidKey] = scope_identity()</c>, and
    ///     VistaDB rejects the Decimal-to-UniqueIdentifier comparison with engine error 558
    ///     ("Invalid operand(s) data type for operator: ="). Restrict to columns whose property carries
    ///     the <see cref="VistaDBValueGenerationStrategy.IdentityColumn" /> strategy — the same check
    ///     used by <c>VistaDBModificationCommandBatch.RequiresIdentityInsert</c>.
    /// </remarks>
    protected override bool IsIdentityOperation(IColumnModification modification)
    {
        if (!base.IsIdentityOperation(modification))
        {
            return false;
        }

        if (modification.Property is { } property
            && property.DeclaringType.GetTableName() is { } tableName)
        {
            var storeObject = StoreObjectIdentifier.Table(tableName, property.DeclaringType.GetSchema());
            return property.GetValueGenerationStrategy(storeObject) == VistaDBValueGenerationStrategy.IdentityColumn;
        }

        return false;
    }

