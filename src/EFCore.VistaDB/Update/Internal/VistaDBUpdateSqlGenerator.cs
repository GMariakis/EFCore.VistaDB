    /// <remarks>
    ///     <para>
    ///         For the common case — INSERT into a table whose only read-back column is an auto-generated
    ///         IDENTITY PK — we emit <c>INSERT … ; SELECT scope_identity()</c> instead of the base
    ///         <c>INSERT … ; SELECT [Id] FROM [T] WHERE @@ROWCOUNT = 1 AND [Id] = scope_identity()</c>.
    ///     </para>
    ///     <para>
    ///         <b>Why:</b> the base WHERE-clause approach is fragile in VistaDB during long multi-INSERT
    ///         batches (e.g., GraphUpdates spec-test fixture seed). The bisection probe (Plan §11)
    ///         confirmed that with the WHERE clause reduced to <c>[Id] = scope_identity()</c>, the
    ///         GraphUpdates seed still fails — meaning <c>scope_identity()</c> in the WHERE position
    ///         returns NULL or a stale value after several preceding INSERTs. The scalar projection
    ///         <c>SELECT scope_identity()</c> doesn't involve the WHERE clause's expression evaluation
    ///         path, so it should bypass whatever VistaDB engine quirk is in play. The
    ///         <c>ScopeIdentityProbeTest</c> in the FunctionalTests project already verifies the scalar
    ///         form returns the correct value.
    ///     </para>
    ///     <para>
    ///         For more complex inserts (computed columns, RowVersion, multiple read-backs) we still
    ///         fall through to the base <see cref="UpdateAndSelectSqlGenerator.AppendInsertAndSelectOperation" />
    ///         WHERE-clause-based path; those scenarios are not exercised by GraphUpdates and remain
    ///         covered by the original behavior.
    ///     </para>
    /// </remarks>
    public override ResultSetMapping AppendInsertOperation(
        StringBuilder commandStringBuilder,
        IReadOnlyModificationCommand command,
        int commandPosition,
        out bool requiresTransaction)
    {
        var operations = command.ColumnModifications;
        var readOperations = operations.Where(o => o.IsRead).ToList();

        // Fast-path: only read-back is an auto-generated INTEGER IDENTITY PK column. Emit scalar
        // SELECT scope_identity() instead of the WHERE-clause-based lookup.
        //
        // We must verify the column's ValueGenerationStrategy is IdentityColumn — otherwise this
        // path catches Guid keys generated by NEWSEQUENTIALID, bool keys with HasDefaultValue, etc.
        // where scope_identity() (which returns DECIMAL) is not the right read-back; VistaDB then
        // errors out trying to convert Decimal to Bit / UniqueIdentifier when EF Core consumes the
        // result. The strategy check is the same one VistaDBModificationCommandBatch.RequiresIdentityInsert
        // uses to decide whether to route through DDA.
        if (readOperations.Count == 1
            && readOperations[0] is { IsKey: true, UseCurrentValueParameter: false } idCol
            && idCol.Property is { } idProperty
            && idProperty.GetValueGenerationStrategy(
                   StoreObjectIdentifier.Table(command.TableName, command.Schema))
               == VistaDBValueGenerationStrategy.IdentityColumn)
        {
            var writeOperations = operations.Where(o => o.IsWrite).ToList();
            AppendInsertCommand(commandStringBuilder, command.TableName, command.Schema, writeOperations, readOperations: []);

            commandStringBuilder
                .Append("SELECT scope_identity()")
                .AppendLine(SqlGenerationHelper.StatementTerminator)
                .AppendLine();

            requiresTransaction = true;
            return ResultSetMapping.LastInResultSet;
        }

        return AppendInsertAndSelectOperation(commandStringBuilder, command, commandPosition, out requiresTransaction);

        // VistaDB: no analog — VistaDB does not support the OUTPUT clause, so we never take the
        // SqlServer OUTPUT-based path. Original SqlServer logic preserved for future revival.
        /*
            if (command.ColumnModifications.All(o => !o.IsRead) || CanUseOutputClause(command))
            {
                return AppendInsertReturningOperation(commandStringBuilder, command, commandPosition, out requiresTransaction);
            }

            var table = StoreObjectIdentifier.Table(command.TableName, command.Schema);

            return command.ColumnModifications.All(o =>
                !o.IsKey
                || !o.IsRead
                || o.Property?.GetValueGenerationStrategy(table) == SqlServerValueGenerationStrategy.IdentityColumn)
                ? AppendInsertAndSelectOperation(commandStringBuilder, command, commandPosition, out requiresTransaction)
                : AppendInsertSingleRowWithOutputInto(
