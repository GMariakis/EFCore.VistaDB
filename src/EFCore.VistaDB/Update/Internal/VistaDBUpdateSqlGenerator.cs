    ///     doing so can result in application failures when updating to a new Entity Framework Core release.
    /// </summary>
    protected override void AppendIdentityWhereCondition(StringBuilder commandStringBuilder, IColumnModification columnModification)
    {
        SqlGenerationHelper.DelimitIdentifier(commandStringBuilder, columnModification.ColumnName);
        commandStringBuilder.Append(" = ");

        // When the caller supplied an explicit value for an IDENTITY column (the IDENTITY_INSERT path —
        // see VistaDBModificationCommandBatch.AddCommand), `scope_identity()` returns NULL because no
        // identity was generated. The SELECT-back's WHERE clause must then look up the row by the
        // explicit value parameter instead — otherwise EF Core sees 0 rows and throws
        // DbUpdateConcurrencyException. UseCurrentValueParameter is true exactly when the explicit value
        // was written into the INSERT.
        if (columnModification.UseCurrentValueParameter)
        {
            SqlGenerationHelper.GenerateParameterNamePlaceholder(commandStringBuilder, columnModification.ParameterName!);
        }
        else
        {
            commandStringBuilder.Append("scope_identity()");
        }
    }

